using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text.RegularExpressions;

public static class PanCafeAdminWriter {
 public static void Initialize(string db,string client) {
  if(PanCafeReadOnly.Query(db,client,"SELECT RDB$RELATION_NAME AS NAME FROM RDB$RELATIONS WHERE RDB$RELATION_NAME='STECH_ADMIN_CHANGES'").Count==0)
   PanCafeReadOnly.Write(db,client,"CREATE TABLE STECH_ADMIN_CHANGES (OPID VARCHAR(36) NOT NULL PRIMARY KEY, MEMBERID INTEGER NOT NULL, USERNAME VARCHAR(32) NOT NULL, DELTA BIGINT NOT NULL, BONUSDELTA BIGINT NOT NULL, EXPECTED BIGINT NOT NULL, EXPECTEDBONUS BIGINT NOT NULL, REASON VARCHAR(160) NOT NULL, BALANCEAFTER DECIMAL(18,2) NOT NULL, BONUSAFTER DECIMAL(18,2) NOT NULL, CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL)",null);
 }
 public static List<Dictionary<string,string>> Adjust(string db,string client,int id,string user,long delta,long bonus,long expected,long expectedBonus,string reason,string op) {
  Guid operation;
  if(id<1 || !Regex.IsMatch(user??"",@"\A[a-zA-Z0-9_.]{1,32}\z") || !Guid.TryParse(op,out operation) || Math.Abs(delta)>1000000 || Math.Abs(bonus)>1000000 || delta==0 || expected<0 || expected>100000000 || expectedBonus<0 || expectedBonus>expected || reason==null || reason.Trim().Length<5 || reason.Length>160 || (bonus!=0 && bonus!=delta)) throw new ArgumentException("Invalid adjustment");
  string sql=@"EXECUTE BLOCK(P_OP VARCHAR(36)=?,P_ID INTEGER=?,P_USER VARCHAR(32)=?,P_DELTA BIGINT=?,P_BONUS BIGINT=?,P_EXPECTED BIGINT=?,P_EXPECTEDBONUS BIGINT=?,P_REASON VARCHAR(160)=?)
RETURNS(RESULT_CODE VARCHAR(12),BALANCE_TL DECIMAL(18,2),BONUS_TL DECIMAL(18,2)) AS
DECLARE N INTEGER;
BEGIN
 SELECT COUNT(*) FROM STECH_ADMIN_CHANGES WHERE OPID=:P_OP INTO :N;
 IF(N>0) THEN BEGIN
  SELECT COUNT(*) FROM STECH_ADMIN_CHANGES WHERE OPID=:P_OP AND MEMBERID=:P_ID AND USERNAME=:P_USER AND DELTA=:P_DELTA AND BONUSDELTA=:P_BONUS AND EXPECTED=:P_EXPECTED AND EXPECTEDBONUS=:P_EXPECTEDBONUS AND REASON=:P_REASON INTO :N;
  IF(N=1) THEN BEGIN
   SELECT BALANCEAFTER,BONUSAFTER FROM STECH_ADMIN_CHANGES WHERE OPID=:P_OP INTO :BALANCE_TL,:BONUS_TL;
   RESULT_CODE='ok';
  END ELSE RESULT_CODE='conflict';
  SUSPEND; EXIT;
 END
 IF(P_EXPECTED+P_DELTA<0 OR P_EXPECTEDBONUS+P_BONUS<0 OR P_EXPECTED+P_DELTA<P_EXPECTEDBONUS+P_BONUS OR P_EXPECTED+P_DELTA>100000000) THEN BEGIN RESULT_CODE='invalid'; SUSPEND; EXIT; END
 UPDATE MEMBERS SET BAKIYE=CAST(COALESCE(BAKIYE,0) AS DECIMAL(18,2))+:P_DELTA/CAST(100 AS DECIMAL(18,2)), AVAILBONUS=CAST(COALESCE(AVAILBONUS,0) AS DECIMAL(18,2))+:P_BONUS/CAST(100 AS DECIMAL(18,2))
 WHERE ID=:P_ID AND USERNAME=:P_USER AND ACCSTATUS=1 AND CAST(COALESCE(BAKIYE,0) AS DECIMAL(18,2))=:P_EXPECTED/CAST(100 AS DECIMAL(18,2)) AND CAST(COALESCE(AVAILBONUS,0) AS DECIMAL(18,2))=:P_EXPECTEDBONUS/CAST(100 AS DECIMAL(18,2));
 IF(ROW_COUNT<>1) THEN BEGIN RESULT_CODE='stale'; SUSPEND; EXIT; END
 SELECT CAST(BAKIYE AS DECIMAL(18,2)),CAST(AVAILBONUS AS DECIMAL(18,2)) FROM MEMBERS WHERE ID=:P_ID AND USERNAME=:P_USER INTO :BALANCE_TL,:BONUS_TL;
 INSERT INTO STECH_ADMIN_CHANGES(OPID,MEMBERID,USERNAME,DELTA,BONUSDELTA,EXPECTED,EXPECTEDBONUS,REASON,BALANCEAFTER,BONUSAFTER) VALUES(:P_OP,:P_ID,:P_USER,:P_DELTA,:P_BONUS,:P_EXPECTED,:P_EXPECTEDBONUS,:P_REASON,:BALANCE_TL,:BONUS_TL);
 INSERT INTO MEMBERSHISTORY(MEMBERS_USERNAME,TERMINALNAME,MIKTAR,KALAN,NOTE) VALUES(:P_USER,'S TECH Admin',:P_DELTA/CAST(100 AS DECIMAL(18,2)),:BALANCE_TL,'S TECH admin '||:P_OP||' '||:P_REASON);
 RESULT_CODE='ok'; SUSPEND;
END";
  return PanCafeReadOnly.Write(db,client,sql,new string[]{operation.ToString(),id.ToString(CultureInfo.InvariantCulture),user,delta.ToString(CultureInfo.InvariantCulture),bonus.ToString(CultureInfo.InvariantCulture),expected.ToString(CultureInfo.InvariantCulture),expectedBonus.ToString(CultureInfo.InvariantCulture),reason});
 }
}
