const { _electron: electron } = require('playwright');
const { mkdtemp, mkdir, rm, writeFile } = require('node:fs/promises');
const { tmpdir } = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const dataDir = await mkdtemp(path.join(tmpdir(), 'stech-kiosk-ui-'));
  const output = path.join(__dirname, '../docs/screenshots'); await mkdir(output, { recursive:true });
  await writeFile(path.join(dataDir,'kiosk.config.json'), JSON.stringify({ mode:'demo', station:'S TECH · Merkez', idleSeconds:30 }));
  const app = await electron.launch({ args:[path.join(__dirname, '..'), '--windowed'], env:{ ...process.env, STECH_KIOSK_DATA_DIR:dataDir } });
  const page = await app.firstWindow(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.getByRole('heading', { name:'Üye kartını okut' }).waitFor();
    await page.screenshot({ path:path.join(output,'01-welcome.png') });
    await page.keyboard.type('DEMO0001', { delay:30 }); await page.keyboard.press('Enter');
    await page.getByRole('heading', { name:'Merhaba, Kaan.' }).waitFor();
    await page.screenshot({ path:path.join(output,'02-home.png') });
    await page.getByRole('button', { name:'Bakiye yükle', exact:true }).first().click();
    await page.getByRole('button', { name:'POS ile ödemeye geç' }).waitFor({ state:'visible' });
    await page.waitForFunction(() => !document.querySelector('[data-action="pay"]').disabled);
    await page.screenshot({ path:path.join(output,'03-topup.png') });
    await page.getByRole('button', { name:'POS ile ödemeye geç' }).click();
    await page.getByRole('heading', { name:'Kartını POS cihazına okut.' }).waitFor();
    await page.screenshot({ path:path.join(output,'04-pos.png') });
    await page.getByRole('button', { name:'Ödemeyi onayla' }).click();
    await page.getByRole('heading', { name:'Hazırsın. İyi oyunlar!' }).waitFor();
    assert.match(await page.locator('.payment-receipt').innerText(), /962,50/);
    await page.screenshot({ path:path.join(output,'05-success.png') });
    await page.getByRole('button', { name:'Ana ekrana dön' }).click();
    await page.getByRole('button', { name:'İşlem geçmişi', exact:true }).click();
    await page.locator('.history-panel .transaction').first().waitFor();
    await page.screenshot({ path:path.join(output,'06-history.png') });
    await page.getByRole('button', { name:'Profilim', exact:true }).click();
    await page.screenshot({ path:path.join(output,'07-profile.png') });
    await page.getByRole('button', { name:'Kampanyalar', exact:true }).click();
    await page.getByRole('button', { name:'Kampanyayı incele' }).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('button', { name:'Geri dön', exact:true }).click();
    await page.getByRole('button', { name:'Oturumu bitir', exact:true }).click();
    await page.getByRole('button', { name:'Evet, oturumu bitir' }).click();
    await page.getByRole('heading', { name:'Üye kartını okut' }).waitFor();
    await page.getByRole('button', { name:'Deniz olarak dene' }).click();
    await page.getByRole('heading', { name:'Merhaba, Deniz.' }).waitFor();
    assert.match(await page.locator('.balance-value').innerText(), /125,00/);
    assert.equal(await page.getByText('Kaan', { exact:true }).count(), 0);
    await page.getByRole('button', { name:'Bakiye yükle', exact:true }).first().click();
    await page.waitForFunction(() => !document.querySelector('[data-action="pay"]').disabled);
    await page.getByRole('button', { name:'POS ile ödemeye geç' }).click();
    await page.getByRole('button', { name:'Ödemeyi reddet' }).click();
    await page.getByRole('heading', { name:'Tekrar deneyebilirsin.' }).waitFor();
    await page.getByRole('button', { name:'Yeni işlem başlat' }).click();
    await page.getByRole('button', { name:'Ana ekran', exact:true }).click();
    assert.match(await page.locator('.balance-value').innerText(), /125,00/);
    // Exercise idle warning/expiry without waiting in real time.
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('kiosk:countdown', 10));
    await page.getByRole('heading', { name:'Hâlâ burada mısın?' }).waitFor();
    await page.screenshot({ path:path.join(output,'08-idle.png') });
    await page.getByRole('button', { name:'Buradayım, devam et' }).click();
    await page.getByRole('button', { name:'Profilim', exact:true }).click();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1024, 768));
    await page.waitForTimeout(200);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path:path.join(output,'09-profile-1024.png') });
    assert.deepEqual(errors, []);
    console.log('Electron UI verified: NFC keyboard login, topup, approval, decline, history, campaign, profile, account isolation, idle modal, 1024px layout.');
  } finally { await app.close(); await rm(dataDir, { recursive:true, force:true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
